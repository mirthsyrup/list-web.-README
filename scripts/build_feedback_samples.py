"""Embed the six approved MP3s as PCM for synchronous offline WebAudio playback."""
from pathlib import Path
import base64,hashlib,json,subprocess

ROOT=Path(__file__).resolve().parents[1]
SAMPLES={"D1":"damage-light.mp3","D2":"damage-heavy.mp3","F1":"critical-failure.mp3","H10":"heal-light.mp3","H6":"heal-heavy.mp3","S16":"critical-success.mp3"}
def build():
    bank={}
    for identifier,name in SAMPLES.items():
        path=ROOT/'site/assets/sounds'/name
        pcm=subprocess.check_output(['ffmpeg','-v','error','-i',str(path),'-f','s16le','-ac','1','-ar','48000','-'])
        if not pcm or len(pcm)%2:raise ValueError('Invalid PCM: '+name)
        bank[identifier]={"sampleRate":48000,"frames":len(pcm)//2,
                          "mp3Sha256":hashlib.sha256(path.read_bytes()).hexdigest(),
                          "pcm":base64.b64encode(pcm).decode()}
    license='''/* Approved D1/D2/H10/H6/S16/F1 recordings: CC0 Kenney and VSCO2 samples,
   https://kenney.nl/assets/impact-sounds and https://kenney.nl/assets/rpg-audio.
   Original editing and synthesis for List. Sources and CC0 notice in assets/sounds.
   Generated by scripts/build_feedback_samples.py; no added sound layers. */
'''
    source=license+"window.ListFeedbackSamples=Object.freeze("+json.dumps(bank,separators=(',',':'))+");\n"
    (ROOT/'site/feedback-samples.js').write_text(source)
    return {identifier:{k:v for k,v in data.items() if k!='pcm'} for identifier,data in bank.items()}
if __name__=='__main__':print(json.dumps(build(),indent=2))

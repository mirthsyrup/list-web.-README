"""Build offline caches for the unified app, direct entry and legacy redirect."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]


def resources(directory):
    return sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / directory).rglob('*')
                  if p.is_file() and p.name not in ('sw.js', 'README.md')
                  and '/assets/sounds/' not in p.as_posix())


def worker(cache, files):
    return """/* Generated by scripts/build_offline.py; cache data only for this version. */
const CACHE=%s;
const FILES=%s;
const urls=new Set(FILES.map(path=>new URL(path,self.location.href).href));
self.addEventListener('install',event=>event.waitUntil(
 caches.open(CACHE).then(cache=>cache.addAll(FILES)).then(()=>self.skipWaiting())
));
self.addEventListener('activate',event=>event.waitUntil(
 caches.keys().then(keys=>Promise.all(keys.filter(key=>key.startsWith(%s)&&key!==CACHE).map(key=>caches.delete(key)))).then(()=>self.clients.claim())
));
self.addEventListener('fetch',event=>{
 if(event.request.method!=='GET')return;
 const url=new URL(event.request.url);url.search='';url.hash='';
 if(!urls.has(url.href))return;
 event.respondWith(caches.open(CACHE).then(async cache=>{
  const saved=await cache.match(event.request,{ignoreSearch:true});
  if(event.request.mode!=='navigate'&&saved)return saved;
  try{const response=await fetch(event.request);if(response.ok){await cache.put(url.href,response.clone());return response;}if(saved)return saved;return response;}
  catch(error){if(saved)return saved;throw error;}
 }));
});
""" % (json.dumps(cache), json.dumps(files, ensure_ascii=False, separators=(',', ':')),
       json.dumps(cache.rsplit('-', 1)[0] + '-'))


def build():
    version = json.loads((ROOT / 'package.json').read_text())['version']
    site = resources('site')
    fantasy = resources('fantasy')
    for directory, files in [('site', site), ('fantasy', site + fantasy)]:
        relative = [Path('../' + p).as_posix() for p in files]
        relative += ['./']
        (ROOT / directory / 'sw.js').write_text(worker('list-' + directory + '-' + version, relative))
    archive = re.search(r"fetch\('([^']+\.zip)'", (ROOT / 'index.html').read_text())[1]
    (ROOT / 'sw.js').write_text(worker('list-public-' + version, ['./', 'index.html', 'manifest.webmanifest', 'fantasy/', 'fantasy/index.html', archive] + site))


if __name__ == '__main__':
    build()
